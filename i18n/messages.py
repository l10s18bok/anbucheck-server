# 지원 locale 목록
SUPPORTED_LOCALES = list(MESSAGES.keys())

# 중국어는 지역이 아니라 문자 체계로 갈린다 — 홍콩·마카오도 번체를 쓴다.
_ZH_TRADITIONAL_TAGS = {"TW", "HK", "MO", "HANT"}


def resolve_locale(locale: str | None) -> str:
    """기기 locale → 지원 locale.

    정확히 일치하지 않으면 **언어 코드**로 한 번 더 찾는다. 예전에는 정확 일치만 봐서
    es_MX·pt_PT·fr_CA·de_AT 사용자가 자기 언어 번역이 있는데도 영어를 받았다.
    """
    if not locale:
        return "en_US"
    loc = locale.replace("-", "_")
    if loc in MESSAGES:
        return loc
    parts = loc.split("_")
    lang = parts[0].lower()
    if lang == "zh":
        tags = {p.upper() for p in parts[1:]}
        return "zh_TW" if tags & _ZH_TRADITIONAL_TAGS else "zh_CN"
    for key in MESSAGES:
        if key.split("_")[0] == lang:
            return key
    return "en_US"


# 천 단위 구분자 — 각 언어의 숫자 표기 관례. 목록에 없으면 쉼표.
_THOUSANDS_SEP = {
    "de": ".", "es": ".", "it": ".", "nl": ".", "pt": ".", "tr": ".", "id": ".", "vi": ".",
    "fr": "\u00a0", "ru": "\u00a0", "pl": "\u00a0", "sv": "\u00a0",
}


def format_number(locale: str | None, n: int) -> str:
    """정수를 locale의 천 단위 구분자로 표기한다(예: de 3.412 / fr 3 412 / en 3,412)."""
    lang = resolve_locale(locale).split("_")[0]
    return f"{n:,}".replace(",", _THOUSANDS_SEP.get(lang, ","))


def get_message(locale: str, key: str, **kwargs) -> str:
    """locale에 맞는 메시지 반환. 언어 단위로도 못 찾으면 en_US fallback."""
    msgs = MESSAGES[resolve_locale(locale)]
    template = msgs.get(key) or MESSAGES["en_US"].get(key, key)
    try:
        return template.format(**kwargs) if kwargs else template
    except (KeyError, IndexError):
        return template


def get_steps_message(locale: str, steps: int) -> str:
    """걸음수 본문. 1보면 단수형(`noti_steps_body_one`)이 있는 언어는 그것을 쓴다.

    ru·pl·ar는 숫자에 따라 명사 격이 바뀌어 단수/복수 두 형태로 해결되지 않으므로
    애초에 "라벨: 숫자" 문장으로 번역해 두었다 — 그 언어들에는 _one 키가 없다.
    """
    msgs = MESSAGES[resolve_locale(locale)]
    key = "noti_steps_body_one" if steps == 1 and "noti_steps_body_one" in msgs else "noti_steps_body"
    return get_message(locale, key, steps=format_number(locale, steps))
